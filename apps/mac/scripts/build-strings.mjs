#!/usr/bin/env node
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fragmentsDir = join(root, "i18n", "en");
const outputDir = join(root, "Localization");
const languages = ["en", "pt-BR"];
const header = "/* Generated by apps/mac/scripts/build-strings.mjs from apps/mac/i18n/en/*.json. Do not edit. */\n";

const args = process.argv.slice(2);
const check = args.includes("--check");
const missingIndex = args.indexOf("--missing");

const specifierPattern = /%(?:\d+\$)?[-+ 0#]*\d*(?:\.\d+)?(?:hh|h|ll|l|q|L|z|t|j)?([@dDiuUxXoOfeEgGcCsSpaAF%])/g;

function specifiers(text) {
  const found = [];
  for (const match of text.matchAll(specifierPattern)) {
    if (match[1] === "%") continue;
    found.push(match[0].replace(/^%\d+\$/, "%"));
  }
  return found.sort();
}

function compareKeys(a, b) {
  return a < b ? -1 : a > b ? 1 : 0;
}

function serializeFragment(entries) {
  const sorted = Object.fromEntries(Object.entries(entries).sort(([a], [b]) => compareKeys(a, b)));
  return `${JSON.stringify(sorted, null, 2)}\n`;
}

function escapeStrings(text) {
  return text
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r")
    .replace(/\t/g, "\\t");
}

function loadFragments() {
  const errors = [];
  const merged = new Map();
  const files = readdirSync(fragmentsDir)
    .filter((name) => name.endsWith(".json"))
    .sort();
  for (const name of files) {
    const path = join(fragmentsDir, name);
    const raw = readFileSync(path, "utf8");
    let entries;
    try {
      entries = JSON.parse(raw);
    } catch (error) {
      errors.push(`${name}: invalid JSON (${error.message})`);
      continue;
    }
    if (typeof entries !== "object" || entries === null || Array.isArray(entries)) {
      errors.push(`${name}: must be a flat object of "pt key": "English"`);
      continue;
    }
    for (const [key, value] of Object.entries(entries)) {
      if (typeof value !== "string" || value.trim() === "") {
        errors.push(`${name}: "${key}" needs a non-empty string translation`);
        continue;
      }
      const expected = specifiers(key).join(" ");
      const actual = specifiers(value).join(" ");
      if (expected !== actual) {
        errors.push(`${name}: "${key}" has format specifiers [${expected}] but the translation has [${actual}]`);
      }
      if (key.includes("\\(")) {
        errors.push(`${name}: "${key}" contains a Swift interpolation; use %@ or %lld in the key`);
      }
      const previous = merged.get(key);
      if (previous && previous.value !== value) {
        errors.push(`"${key}" is translated differently in ${previous.file} and ${name}`);
        continue;
      }
      if (!previous) merged.set(key, { value, file: name });
    }
    const normalized = serializeFragment(entries);
    if (raw !== normalized) {
      if (check) errors.push(`${name}: keys are not sorted or the file is not formatted; run the script without --check`);
      else writeFileSync(path, normalized);
    }
  }
  return { merged, errors, files };
}

function render(merged, language) {
  if (language !== "en") return header;
  const lines = [...merged.entries()]
    .sort(([a], [b]) => compareKeys(a, b))
    .map(([key, { value }]) => `"${escapeStrings(key)}" = "${escapeStrings(value)}";`);
  return `${header}\n${lines.join("\n")}\n`;
}

function swiftFiles(path) {
  if (statSync(path).isFile()) return path.endsWith(".swift") ? [path] : [];
  return readdirSync(path)
    .sort()
    .flatMap((name) => swiftFiles(join(path, name)));
}

function reportMissing(merged, paths) {
  const literal = /"((?:[^"\\\n]|\\.)*)"/g;
  let count = 0;
  for (const file of paths.flatMap((path) => swiftFiles(path))) {
    const lines = readFileSync(file, "utf8").split("\n");
    lines.forEach((line, index) => {
      if (line.trim().startsWith("//")) return;
      for (const match of line.matchAll(literal)) {
        const text = match[1];
        if (!/[A-Za-zÀ-ÿ]/.test(text)) continue;
        if (!/[\sÀ-ÿ]/.test(text) && !/^[A-ZÀ-Ý][a-zà-ÿ]+$/.test(text)) continue;
        if (/^[a-z0-9_-]+(\.[a-z0-9_-]+)+$/.test(text)) continue;
        const key = text.replace(/\\"/g, '"').replace(/\\n/g, "\n");
        if (merged.has(key)) continue;
        const interpolation = /\\\((?:[^()]|\([^()]*\))*\)/g;
        if (["%@", "%lld"].some((specifier) => merged.has(key.replace(interpolation, specifier)))) continue;
        const hint = key.includes("\\(") ? "  (interpolated: key uses %@ / %lld)" : "";
        console.log(`${relative(process.cwd(), file)}:${index + 1}: ${text}${hint}`);
        count += 1;
      }
    });
  }
  console.error(`${count} literal(s) without an English translation`);
}

const { merged, errors, files } = loadFragments();
if (errors.length > 0) {
  for (const error of errors) console.error(`error: ${error}`);
  process.exit(1);
}

if (missingIndex !== -1) {
  const paths = args.slice(missingIndex + 1).filter((arg) => !arg.startsWith("--"));
  reportMissing(merged, paths.length > 0 ? paths : [join(root, "Sources")]);
  process.exit(0);
}

let stale = false;
for (const language of languages) {
  const dir = join(outputDir, `${language}.lproj`);
  const path = join(dir, "Localizable.strings");
  const content = render(merged, language);
  let current = null;
  try {
    current = readFileSync(path, "utf8");
  } catch {}
  if (current === content) continue;
  if (check) {
    console.error(`error: ${relative(root, path)} is out of date; run apps/mac/scripts/build-strings.mjs`);
    stale = true;
    continue;
  }
  mkdirSync(dir, { recursive: true });
  writeFileSync(path, content);
}
if (stale) process.exit(1);
console.log(`${merged.size} English strings from ${files.length} fragment(s)`);
